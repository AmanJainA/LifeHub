-- ----------------------------------------------------------------------------
-- 1. PROFILES  (mirrors auth.users, public info needed for Splitwise lookups)
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'New user',
  email text not null,
  avatar text default '🙂',
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles are readable by any signed-in user" on public.profiles;
create policy "profiles are readable by any signed-in user"
  on public.profiles for select
  to authenticated
  using (true);

drop policy if exists "users can update own profile" on public.profiles;
create policy "users can update own profile"
  on public.profiles for update
  to authenticated
  using (auth.uid() = id);

-- Auto-create a profile row whenever a new auth user signs up
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, name, email, avatar)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    new.email,
    '🙂'
  )
  on conflict (id) do nothing;
  return new;
end;
$$ language plpgsql security definer set search_path = public;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- ----------------------------------------------------------------------------
-- 2. LIFE  (tasks, notes, goals, reminders, ideas) — private per user
-- ----------------------------------------------------------------------------
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text,
  priority text not null default 'medium' check (priority in ('high','medium','low')),
  status text not null default 'pending' check (status in ('pending','done')),
  due_date date,
  created_at timestamptz default now()
);

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  content text,
  tags text,
  color text default '#f5a623',
  pinned boolean default false,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  target numeric(12,2) not null,
  current numeric(12,2) default 0,
  unit text default '%',
  deadline date,
  status text not null default 'active' check (status in ('active','done','paused')),
  created_at timestamptz default now()
);

create table if not exists public.reminders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  remind_at timestamptz not null,
  repeat_type text default 'none' check (repeat_type in ('none','daily','weekly','monthly')),
  done boolean default false,
  created_at timestamptz default now()
);

create table if not exists public.ideas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text,
  tag text default 'general' check (tag in ('app','business','feature','general')),
  priority text default 'medium' check (priority in ('high','medium','low')),
  status text default 'new' check (status in ('new','wip','done','shelved')),
  created_at timestamptz default now()
);

-- ----------------------------------------------------------------------------
-- 3. FINANCE  (expenses/income, budgets) — private per user
-- ----------------------------------------------------------------------------
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null check (type in ('income','expense')),
  amount numeric(12,2) not null,
  category text not null,
  description text,
  date date not null,
  created_at timestamptz default now()
);

create table if not exists public.budgets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  amount numeric(12,2) not null,
  month text not null, -- 'YYYY-MM'
  created_at timestamptz default now(),
  unique (user_id, category, month)
);

-- Generic "own rows only" RLS for the private-data tables above
do $$
declare
  t text;
begin
  foreach t in array array['tasks','notes','goals','reminders','ideas','expenses','budgets']
  loop
    execute format('alter table public.%I enable row level security;', t);
    execute format('drop policy if exists "own rows only" on public.%I;', t);
    execute format(
      'create policy "own rows only" on public.%I for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);',
      t
    );
  end loop;
end $$;

-- ----------------------------------------------------------------------------
-- 4. SPLITWISE  (groups, members, expenses, shares, settlements) — shared
-- ----------------------------------------------------------------------------
create table if not exists public.sw_groups (
  id bigint generated by default as identity primary key,
  name text not null,
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz default now()
);

create table if not exists public.sw_group_members (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.sw_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz default now(),
  unique (group_id, user_id)
);

create table if not exists public.sw_expenses (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.sw_groups(id) on delete cascade,
  paid_by uuid not null references auth.users(id) on delete cascade,
  description text,
  amount numeric(12,2) not null,
  category text default 'General',
  date date not null default current_date,
  created_at timestamptz default now()
);

create table if not exists public.sw_expense_shares (
  id bigint generated by default as identity primary key,
  expense_id bigint not null references public.sw_expenses(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  share_amount numeric(12,2) not null,
  settled boolean default false,
  unique (expense_id, user_id)
);

create table if not exists public.sw_settlements (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.sw_groups(id) on delete cascade,
  from_user uuid not null references auth.users(id) on delete cascade,
  to_user uuid not null references auth.users(id) on delete cascade,
  amount numeric(12,2) not null,
  note text,
  created_at timestamptz default now()
);

-- Helper: is the current user a member of a given group? (security definer avoids RLS recursion)
create or replace function public.is_group_member(gid bigint)
returns boolean as $$
  select exists (
    select 1 from public.sw_group_members
    where group_id = gid and user_id = auth.uid()
  );
$$ language sql security definer stable set search_path = public;

alter table public.sw_groups enable row level security;
alter table public.sw_group_members enable row level security;
alter table public.sw_expenses enable row level security;
alter table public.sw_expense_shares enable row level security;
alter table public.sw_settlements enable row level security;

-- sw_groups: members can view; any authenticated user can create; creator can update/delete
drop policy if exists "members can view group" on public.sw_groups;
create policy "members can view group" on public.sw_groups
  for select to authenticated using (public.is_group_member(id) or created_by = auth.uid());

drop policy if exists "authenticated users can create groups" on public.sw_groups;
create policy "authenticated users can create groups" on public.sw_groups
  for insert to authenticated with check (created_by = auth.uid());

drop policy if exists "creator can update/delete group" on public.sw_groups;
create policy "creator can update group" on public.sw_groups
  for update to authenticated using (created_by = auth.uid());
create policy "creator can delete group" on public.sw_groups
  for delete to authenticated using (created_by = auth.uid());

-- sw_group_members: members can view membership list; members can add others; users can remove themselves
drop policy if exists "members can view membership" on public.sw_group_members;
create policy "members can view membership" on public.sw_group_members
  for select to authenticated using (public.is_group_member(group_id));

drop policy if exists "members can add members" on public.sw_group_members;
create policy "members can add members" on public.sw_group_members
  for insert to authenticated with check (
    user_id = auth.uid() or public.is_group_member(group_id)
  );

drop policy if exists "members can remove themselves" on public.sw_group_members;
create policy "members can remove themselves" on public.sw_group_members
  for delete to authenticated using (user_id = auth.uid());

-- sw_expenses: any group member can view/add/edit/delete
drop policy if exists "group members manage expenses" on public.sw_expenses;
create policy "group members manage expenses" on public.sw_expenses
  for all to authenticated
  using (public.is_group_member(group_id))
  with check (public.is_group_member(group_id));

-- sw_expense_shares: visible/manageable to members of the parent expense's group
drop policy if exists "group members manage shares" on public.sw_expense_shares;
create policy "group members manage shares" on public.sw_expense_shares
  for all to authenticated
  using (exists (select 1 from public.sw_expenses e where e.id = expense_id and public.is_group_member(e.group_id)))
  with check (exists (select 1 from public.sw_expenses e where e.id = expense_id and public.is_group_member(e.group_id)));

-- sw_settlements: visible to group members; only the payer (from_user) can record it
drop policy if exists "group members view settlements" on public.sw_settlements;
create policy "group members view settlements" on public.sw_settlements
  for select to authenticated using (public.is_group_member(group_id));

drop policy if exists "payer records settlement" on public.sw_settlements;
create policy "payer records settlement" on public.sw_settlements
  for insert to authenticated with check (public.is_group_member(group_id) and (from_user = auth.uid() or to_user = auth.uid()));

drop policy if exists "payer deletes own settlement" on public.sw_settlements;
create policy "payer deletes own settlement" on public.sw_settlements
  for delete to authenticated using (from_user = auth.uid());

